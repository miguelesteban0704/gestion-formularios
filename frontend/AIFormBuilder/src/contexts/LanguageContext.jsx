/**
 * El idioma con el que arranca la app.
 *
 * El orden de las fuentes es el orden de la autoridad:
 *
 *  1. Lo que el usuario ya eligió (guardado en localStorage). Un idioma elegido
 *     es una decisión, no una sugerencia, y un enlace no puede deshacerla.
 *  2. El idioma del alias de la URL (solo rutas del panel). Aquí no hay ninguna
 *     decisión que respetar, así que se respeta la del enlace.
 *  3. El idioma preferido del navegador (para páginas públicas sin sesión de
 *     panel). Así un visitante que nunca haya entrado al panel ve el formulario
 *     en su idioma si lo soportamos.
 *  4. El idioma por defecto (inglés).
 *
 * Se lee aquí y no en un efecto para que la app no llegue a pintar en el idioma
 * equivocado ni un solo frame: la URL y la pantalla nacen ya de acuerdo.
 */
function getInitialLanguage() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (SUPPORTED_LANGUAGES.includes(saved)) return saved;

  const deLaUrl = typeof window === "undefined" ? null : languageFromPath(window.location.pathname);
  if (deLaUrl) return deLaUrl;

  // Fallback: idioma del navegador (solo para rutas que no son del panel).
  if (typeof window !== "undefined" && window.navigator?.language) {
    const browserLang = window.navigator.language.split("-")[0].toLowerCase();
    if (SUPPORTED_LANGUAGES.includes(browserLang)) return browserLang;
  }

  return DEFAULT_LANGUAGE;
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage);
  const dictionary = translations[language];

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const changeLanguage = useCallback((nextLanguage) => {
    if (SUPPORTED_LANGUAGES.includes(nextLanguage)) setLanguage(nextLanguage);
  }, []);

  const t = useCallback(
    (key) => dictionary[key] ?? translations.en[key] ?? key,
    [dictionary],
  );

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, language);
    } catch {
      /* almacenamiento no disponible: la preferencia no persiste */
    }
  }, [language]);

  const value = useMemo(
    () => ({ language, changeLanguage, t }),
    [language, changeLanguage, t],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}
