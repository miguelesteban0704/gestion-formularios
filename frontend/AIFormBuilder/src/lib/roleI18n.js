export function useRoleT() {
  const { language } = useLanguage();
  const dict = STRINGS[language] || STRINGS.en;
  return (key, ...args) => {
    const v = dict[key] ?? STRINGS.en[key] ?? key;
    return typeof v === "function" ? v(...args) : v;
  };
}
