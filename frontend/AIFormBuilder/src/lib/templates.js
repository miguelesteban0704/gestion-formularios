export function normalizeTemplateForm(form) {
  return {
    title: form.title || "Untitled form",
    description: form.description || "",
    theme: form.theme || "modern",
    settings: form.settings || {},
    questions: (form.questions || []).map((question, index) => ({
      ...question,
      id: question.id || `template_question_${index}`,
      options: Array.isArray(question.options)
        ? question.options.map((option, optionIndex) => typeof option === "object"
          ? { ...option, id: option.id || `template_option_${index}_${optionIndex}`, label: option.label || option.value || "Option" }
          : { id: `template_option_${index}_${optionIndex}`, label: option, value: "" })
        : [],
      validation: question.validation || { minLength: null, maxLength: null, min: null, max: null, pattern: "", message: "" },
    })),
  };
}

