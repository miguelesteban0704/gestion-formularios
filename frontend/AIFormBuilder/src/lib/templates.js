export function localizeTemplateForm(form, language) {
  const translate = (value) => typeof value === "string" ? TRANSLATIONS[language]?.[value] || SPANISH_TEMPLATE_TEXT[value] || value : value;
  return {
    ...form,
    title: translate(form.title),
    description: translate(form.description),
    questions: form.questions.map((question) => ({
      ...question,
      label: translate(question.label),
      content: translate(question.content),
      options: question.options?.map((option) => ({ ...option, label: translate(option.label) })),
    })),
    settings: { ...form.settings, submitButtonText: translate(form.settings?.submitButtonText), thankYouMessage: translate(form.settings?.thankYouMessage) },
  };
}
