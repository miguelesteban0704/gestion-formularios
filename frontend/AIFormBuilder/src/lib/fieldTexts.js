/**
 * Traduce una etiqueta de campo al idioma indicado.
 * Si no hay traducción, devuelve el texto original.
 */
export function translateLabel(text, language) {
  if (!text) return text;
  const langKey = language === "es" ? "es" : "en";
  return FIELD_LABELS[langKey]?.[text] || text;
}